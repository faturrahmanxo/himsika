-- 1. TABEL LOMBA & BEASISWA
CREATE TABLE IF NOT EXISTS public.lomba (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    organizer TEXT NOT NULL,
    description TEXT,
    deadline_pendaftaran TEXT,
    deadline_pengumpulan TEXT,
    benefit TEXT,
    categories JSONB DEFAULT '[]'::jsonb,
    deadline_timestamp BIGINT,
    registration_url TEXT,
    guidebook_url TEXT,
    instagram_url TEXT,
    contacts JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. TABEL ARTIKEL & BERITA
CREATE TABLE IF NOT EXISTS public.artikel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'Berita',
    date TEXT,
    datetime TEXT,
    image TEXT,
    excerpt TEXT,
    content JSONB,
    author TEXT DEFAULT 'HIMSIKA',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TABEL PRESTASI MAHASISWA
CREATE TABLE IF NOT EXISTS public.prestasi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    peringkat TEXT NOT NULL,
    judul TEXT NOT NULL,
    pemenang JSONB DEFAULT '[]'::jsonb,
    gambar TEXT,
    instagram_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. TABEL GALERI KEGIATAN
CREATE TABLE IF NOT EXISTS public.galeri (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    album TEXT NOT NULL,
    album_slug TEXT,
    foto TEXT NOT NULL,
    caption TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. TABEL PENGURUS & STRUKTUR ORGANISASI (PROFIL)
CREATE TABLE IF NOT EXISTS public.pengurus (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama TEXT NOT NULL,
    jabatan TEXT NOT NULL,
    kelompok TEXT NOT NULL DEFAULT 'bph',
    foto TEXT,
    instagram TEXT,
    linkedin TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ============================================================
-- KEAMANAN: ROW LEVEL SECURITY (RLS)
-- Publik bisa membaca (SELECT), Admin (authenticated) bisa mengelola (ALL)
-- ============================================================

